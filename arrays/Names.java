class Names {
    public static void main(String[] args) {

        String[] names = {
            "Prince",
            "Anant",
            "Kartik",
            "Madhav",
            "Piyush",
            "Lukesh"
        };

        System.out.println("Names:");
        for (int i = 0; i < names.length; i++) {
            System.out.println(names[i]);
        }
    }
}